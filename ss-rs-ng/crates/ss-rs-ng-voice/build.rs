//! Bake a pack's voice files into the binary, so a deployment is one file.
//!
//! Opt-in, because the files are the user's and are tens of MB:
//!
//! ```text
//! SSRSNG_BAKE=rs | ss | rs,ss          which packs
//! SSRSNG_RS_SPEECH / SSRSNG_SS_SPEECH  their `speech` directories
//!                                      [../RealSpeak/speech, ../ScanSoft/speech beside ss-rs-ng]
//! ```
//!
//! What gets baked is `xlate/<pack>_files.txt`: every file the engine opens,
//! as recorded by `xtask engcorpus --files`. Without SSRSNG_BAKE the crate
//! builds with empty trees and the binary needs `--speech`.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn find_ci(root: &Path, rel: &str) -> Option<PathBuf> {
    let mut p = root.to_path_buf();
    for comp in rel.split('/') {
        let exact = p.join(comp);
        if exact.exists() {
            p = exact;
            continue;
        }
        p = fs::read_dir(&p)
            .ok()?
            .filter_map(|e| e.ok())
            .find(|e| e.file_name().to_string_lossy().eq_ignore_ascii_case(comp))?
            .path();
    }
    Some(p)
}

fn tree(pack: &str, ng: &Path, bake: &[String], default: &str) -> String {
    let name = pack.to_ascii_uppercase();
    if !bake.iter().any(|b| b == pack) {
        return format!("pub static {name}: Tree = &[];\n");
    }
    let var = format!("SSRSNG_{name}_SPEECH");
    println!("cargo:rerun-if-env-changed={var}");
    let speech = env::var_os(&var)
        .map(PathBuf::from)
        .unwrap_or_else(|| ng.parent().unwrap().join(default).join("speech"));
    let list_path = ng.join("xlate").join(format!("{pack}_files.txt"));
    println!("cargo:rerun-if-changed={}", list_path.display());
    let list = fs::read_to_string(&list_path).expect("reading the file list");
    let mut out = format!("pub static {name}: Tree = &[\n");
    let mut total = 0u64;
    let mut n = 0;
    for rel in list.lines().filter_map(|l| l.strip_prefix("open ")) {
        let real = find_ci(&speech, rel)
            .unwrap_or_else(|| panic!("SSRSNG_BAKE={pack}: {rel} is not in {}", speech.display()));
        total += fs::metadata(&real).map(|m| m.len()).unwrap_or(0);
        println!("cargo:rerun-if-changed={}", real.display());
        out.push_str(&format!("    ({rel:?}, include_bytes!({:?})),\n", real));
        n += 1;
    }
    out.push_str("];\n");
    println!(
        "cargo:warning=ss-rs-ng-voice: {pack}: {n} files, {:.1} MB built in from {}",
        total as f64 / 1048576.0,
        speech.display()
    );
    out
}

fn main() {
    println!("cargo:rerun-if-env-changed=SSRSNG_BAKE");
    let bake: Vec<String> = env::var("SSRSNG_BAKE")
        .unwrap_or_default()
        .split(',')
        .map(|s| s.trim().to_ascii_lowercase())
        .filter(|s| !s.is_empty())
        .collect();
    let crate_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let ng = crate_dir.parent().unwrap().parent().unwrap().to_path_buf();
    let mut out = String::from("// Generated by build.rs -- the voice files, verbatim.\n\n");
    out.push_str(&tree("rs", &ng, &bake, "RealSpeak"));
    out.push_str(&tree("ss", &ng, &bake, "ScanSoft"));
    let dst = PathBuf::from(env::var("OUT_DIR").unwrap()).join("voice.rs");
    fs::write(dst, out).expect("writing voice.rs");
}
